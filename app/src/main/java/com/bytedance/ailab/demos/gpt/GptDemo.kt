                lastMsg = if (headOn[h]) Bi("头 ${h + 1}：显示", "Head ${h + 1}: shown") else Bi("头 ${h + 1}：隐藏", "Head ${h + 1}: hidden")
            }
            name.startsWith("Bar") -> {
