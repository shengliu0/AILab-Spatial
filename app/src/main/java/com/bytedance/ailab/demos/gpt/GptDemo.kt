                applyPreset(i); picksAtPreset = picks
                lastMsg = Bi("预设 ${i + 1}：前向计算重新跑一遍", "Preset ${i + 1}: the forward pass runs again")
            }
            name.startsWith("Head") -> {
                val h = name.removePrefix("Head").toIntOrNull() ?: return
