    private const val ATLAS_COLS = 16
    private val atlasRows get() = (atlas.size + ATLAS_COLS - 1) / ATLAS_COLS
    /** All glyphs as one white-on-transparent texture (straight alpha); every glyph quad samples it. */
    private val atlasImg: Image by lazy {
        val c = atlas.cell; val img = Image(ATLAS_COLS * c, atlasRows * c)
        for (g in 0 until atlas.size) {
            val ox = (g % ATLAS_COLS) * c; val oy = (g / ATLAS_COLS) * c
            for (y in 0 until c) for (x in 0 until c) {
                val a = atlas.alpha[g * c * c + y * c + x].toInt() and 0xFF
                img.px[(oy + y) * img.w + ox + x] = (a shl 24) or 0xFFFFFF
            }
        }
        img
    }
    private val glyphMeshes = HashMap<Int, MeshData>()
    /** A unit quad (facing +Z) whose UVs cut glyph [c] out of the atlas; one mesh per character, shared. */
    private fun glyphMesh(c: Char): MeshData {
        val g = atlas.indexOf(c).let { if (it < 0) atlas.indexOf('?') else it }
        return glyphMeshes.getOrPut(g) {
            val cell = atlas.cell.toFloat(); val w = ATLAS_COLS * cell; val h = atlasRows * cell
            val u0 = ((g % ATLAS_COLS) * cell + 1f) / w; val u1 = ((g % ATLAS_COLS + 1) * cell - 1f) / w
            val v0 = ((g / ATLAS_COLS) * cell + 1f) / h; val v1 = ((g / ATLAS_COLS + 1) * cell - 1f) / h
            quad(u0, v0, u1, v1)
        }
    }

