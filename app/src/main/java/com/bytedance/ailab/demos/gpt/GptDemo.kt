    /** How a token is written in 2-D text (readout, panel buttons): the story-start token as a pilcrow. */
    private fun show(c: Char) = if (c == '\n') '¶' else c

    private fun focusSlot() = if (hl >= 0) hl else nv - 1

    /**
     * The head to describe in the readout for the focus token: the most concentrated one among the visible
     * heads/layers, preferring a real look-back (2+ tokens away) over "itself" or "the previous token".
     */
    private fun focusHead(): Triple<Int, Int, List<Pair<Int, Double>>>? {
        val tr = trace ?: return null
        val q = focusSlot() + fv - ctxStart
        var best: Triple<Int, Int, List<Pair<Int, Double>>>? = null; var bs = -1.0
        for (l in 0 until 2) {
            if (layerSel != 2 && layerSel != l) continue
            for (h in 0 until 4) {
                if (!headOn[h]) continue
                val row = tr.att[l][h][q]
                val keys = (0..q).map { it to row[it] }.sortedByDescending { it.second }
                val score = keys[0].second * (if (q - keys[0].first >= 2) 1.0 else 0.6)
                if (score > bs) { bs = score; best = Triple(l, h, keys) }
            }
        }
        return best
    }

    private fun updateReadout() {
        if (probs.isEmpty()) return
        val n = seq.size
        val tail = (if (n > 10) "…" else "") + seq.subList(maxOf(0, n - 10), n).map { show(model.charOf(it)) }.joinToString("")
        val t3 = (0 until 3).map { top[it] }
        val l1 = tr("输入 %s → 下一个字：%s（T = %.2f）".format(tail, t3.joinToString(" · ") { "%s%.1f%%".format(tr("【%s】", "%s ").format(show(model.charOf(it))), probs[it] * 100) }, temperature),
            "Next-token top 3: %s (T = %.2f, %d tokens in context) — characters on the fan".format(
                t3.joinToString(" · ") { "%.1f%%".format(probs[it] * 100) }, temperature, n - ctxStart))
        val fh = focusHead()
        val fs = focusSlot()
        val l2 = if (fh == null) tr("所有注意力头都已隐藏 —— 捏书架上的 H1–H4 打开", "All heads hidden — pinch H1–H4 on the shelf to show them")
        else {
            val (l, h, keys) = fh
            val q = fs + fv - ctxStart
            val k2 = keys.take(2).filter { it.second >= 0.01 }
            val fc = show(model.charOf(seq[fv + fs]))
            val who = if (hl >= 0) tr("高亮的字【%s】".format(fc), "The highlighted token") else tr("最后一个字【%s】".format(fc), "The last token")
            tr("%s · 第 %d 层 头 %d 最关注：%s", "%s · layer %d head %d reads %s").format(who, l + 1, h + 1,
                k2.joinToString(tr("、", ", ")) { (j, w) ->
                    val c = show(model.charOf(seq[ctxStart + j])); val pc = (w * 100).roundToInt()
                    when (q - j) {
                        0 -> tr("它自己 %d%%".format(pc), "itself (%d%%)".format(pc))
                        1 -> tr("【%s】%d%%".format(c, pc), "the previous token (%d%%)".format(pc))
                        else -> tr("【%s】%d%%".format(c, pc), "the token %d back (%d%%)".format(q - j, pc))
                    }
                })
        }
        val l3 = tr("注意力 = 对前面字的加权查找（线只连向左边）；模型只做一件事：预测下一个字。",
            "Attention = a weighted lookup of earlier tokens (threads only go left); the model only predicts the next token.")
        readoutText = "$l1\n$l2\n$l3"
    }

