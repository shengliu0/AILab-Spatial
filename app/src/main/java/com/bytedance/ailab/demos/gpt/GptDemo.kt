    // ---------------------------------------------------------------- model state

    private fun loadPreset(i: Int, animate: Boolean) {
        presetIdx = i
        seq.clear(); for (c in PRESETS[i]) seq += model.idOf(c)
        presetLen = seq.size
        hl = -1; autoGen = false; autoCount = 0; phase = Phase.IDLE; phaseT = 0f
        recompute()
        if (animate) { phase = Phase.GROW; grow = 0f } else grow = 1f
    }

    /** The forward pass: only when the token sequence changes (~2 ms on the Mac JVM for 32 tokens). */
    private fun recompute() {
        val n = seq.size
        nv = minOf(n, W); fv = n - nv; ctxStart = n - minOf(n, model.ctx)
        val tr = model.forward(seq.subList(ctxStart, n).toIntArray())
        trace = tr
        for (r in 0 until 3) for (k in 0 until nv) model.pca(r, tr.rows[r][fv + k - ctxStart], cellVal[r][k])
        if (hl >= nv) hl = -1
        probsDirty = true; threadsDirty = true; layoutDirty = true; slotsDirty = true
    }

    private fun updateProbs() {
        val tr = trace ?: return
        probs = Sampling.softmax(tr.lastLogits, temperature.toDouble())
        top = Sampling.topK(probs, NBAR)
    }

    // ---------------------------------------------------------------- actions (also used by the lesson)

    fun applyPreset(i: Int) { loadPreset(i, animate = true); layoutDirty = true }

    fun setTemperature(t: Float) {
        val v = t.coerceIn(T_MIN, T_MAX)
        if (v != temperature) { temperature = v; probsDirty = true }
    }

    fun highlight(slot: Int) { hl = if (slot in 0 until nv) slot else -1; threadsDirty = true; layoutDirty = true; slotsDirty = true }

    fun toggleHead(h: Int) { headOn[h] = !headOn[h]; threadsDirty = true }

    fun selectLayer(s: Int) { layerSel = s; threadsDirty = true }

    fun startGenerate() { if (!autoGen) { autoGen = true; autoCount = 0; pause = 0f } }

    fun stopGenerate() { autoGen = false }

    /** Choose token [tok] as the next character; [fromRank] = which fan tile it flies from (-1: the hub). */
    private fun choose(tok: Int, fromRank: Int) {
        if (phase == Phase.FLY) return
        flyTok = tok
        flyFrom = if (fromRank in 0 until NBAR) barTiles[fromRank].pos else HUB
        flyShift = seq.size >= W
        phase = Phase.FLY; phaseT = 0f; grow = 0f
        flyer.setMesh(glyphMesh(model.charOf(tok))); flyer.visible = true
        layoutDirty = true; threadsDirty = true; slotsDirty = true
    }

    private fun land() {
        seq += flyTok; picks++; autoCount++
        if (flyShift && hl >= 0) hl -= 1
        flyer.visible = false
        recompute()
        phase = Phase.GROW; phaseT = 0f; grow = 0f
        if (autoGen && sentenceDone()) autoGen = false
    }

    /** Append characters immediately (review states). */
    private fun appendNow(s: String) { for (c in s) seq += model.idOf(c); picks += s.length; recompute(); grow = 1f; phase = Phase.IDLE }

    private fun sentenceDone(): Boolean {
        val c = model.charOf(seq.last())
        if (c == '\n' || autoCount >= 16) return true
        var open = 0
        for (i in seq.indices.reversed()) { val x = model.charOf(seq[i]); if (x == '\n') break; if (x == '「') open++; if (x == '」') open-- }
        return open <= 0 && (c == '。' || c == '！' || c == '？' || c == '」')
    }

    // ---------------------------------------------------------------- per frame

    override fun update(dt: Float) {
        val sp = SPEEDS[speedIdx]
        when (phase) {
            Phase.FLY -> {
                phaseT = (phaseT + dt * sp / 0.6f).coerceAtMost(1f)
                if (phaseT >= 1f) land() else { layoutDirty = true; if (flyShift) slotsDirty = true }
            }
            Phase.GROW -> {
                grow = (grow + dt * sp / 0.35f).coerceAtMost(1f)
                if (grow >= 1f) { phase = Phase.IDLE; pause = 0f }
                layoutDirty = true; threadsDirty = true
            }
            Phase.IDLE -> if (autoGen) {
                pause += dt * sp
                if (pause >= 0.3f) {
                    if (probsDirty) updateProbs()
                    val tok = Sampling.sample(probs, rng.nextDouble())
                    choose(tok, top.indexOf(tok))
                }
            }
        }
        refresh()
    }

    private fun refresh() {
        if (probsDirty) { updateProbs(); probsDirty = false; layoutDirty = true }
        if (layoutDirty) { layout(); layoutDirty = false }
        if (threadsDirty) { placeThreads(); threadsDirty = false }
        updateReadout()
        updateLabels()
    }

    private fun shiftNow(): Float = if (phase == Phase.FLY && flyShift) smooth(phaseT) else 0f
    private fun slotX(k: Int, shift: Float) = X0 + (k - shift) * SX
    private fun fanAngle(k: Int) = ((90.0 - 20.0 * k) * PI / 180.0).toFloat()

    private fun layout() {
        val sh = shiftNow()
        if (slotsDirty) { slotsDirty = false; layoutSlots(sh) }
        // unembedding beam: last column of the top row -> fan hub
        val showFan = phase != Phase.FLY
        val lx = slotX(nv - 1, sh)
        place(beam, P3(lx + 0.03f, ROW_Y[2], ROW_Z[2]), P3(HUB.x - 0.03f, HUB.y, HUB.z), 0.0035f * grow)
        beam.visible = showFan && grow > 0.01f
        // fan
        for (k in 0 until NBAR) {
            val tok = top[k]; val p = if (probs.isNotEmpty()) probs[tok].toFloat() else 0f
            val th = fanAngle(k); val len = maxOf(0.002f, BAR_LMAX * p * grow)
            val r = BAR_R0 + len / 2
            bars[k].pos = P3(HUB.x + r * cos(th), HUB.y + r * sin(th), HUB.z)
            bars[k].rot = Q.axisAngle(0f, 0f, 1f, th)
            bars[k].scale = P3(len, 0.016f, 0.010f)
            bars[k].setMat(if (k == 0) barTopMat else barMat)
            bars[k].visible = showFan
            val c = model.charOf(tok)
            barGlyph[k].setMesh(glyphMesh(c))
            barGlyph[k].setMat(if (c == '\n') glyphDim else glyphWhite)
            val txt = pct(p)
            val rd = DIGIT_R
            for (i in 0 until 3) {
                val ch = txt.getOrNull(i)
                barDigits[k][i].visible = ch != null && showFan
                if (ch != null) {
                    barDigits[k][i].setMesh(glyphMesh(ch))
                    barDigits[k][i].pos = P3(HUB.x + rd * cos(th) + (i - (txt.length - 1) / 2f) * 0.0165f, HUB.y + rd * sin(th), HUB.z + 0.004f)
                }
            }
        }
        // knob: dot angle -135..135 deg over log T, value on its face
        if (knobShownT != temperature) {
            knobShownT = temperature
            val f = (ln(temperature / T_MIN) / ln(T_MAX / T_MIN)).coerceIn(0f, 1f)
            knobSpin.rot = Q.axisAngle(0f, 0f, 1f, ((135.0 - 270.0 * f) * PI / 180.0).toFloat())
            val s = "%.2f".format(java.util.Locale.ROOT, temperature)
            for (i in 0 until 4) knobDigits[i].setMesh(glyphMesh(s[i]))
        }
        for (h in 0 until 4) {
            heads[h].setMat(if (headOn[h]) headOnMats[h] else headOffMats[h])
            for (g in headGlyphs[h]) g.setMat(if (headOn[h]) glyphDark else glyphDim)
        }
        for (i in presets.indices) presets[i].setMat(if (i == presetIdx && picks == picksAtPreset) presetOn else plateMat)
        gen.setMat(if (autoGen) genOn else genIdle)
        // the flying character
        if (phase == Phase.FLY) {
            val to = P3(slotX(if (flyShift) W - 1 else nv, 0f), TOK_Y, TOK_Z + 0.01f)
            val t = smooth(phaseT)
            val mid = P3((flyFrom.x + to.x) / 2, maxOf(flyFrom.y, to.y) + 0.16f, (flyFrom.z + to.z) / 2 + 0.12f)
            val a = flyFrom * ((1 - t) * (1 - t)) + mid * (2 * t * (1 - t)) + to * (t * t)
            flyer.pos = a; flyer.uniformScale(0.07f - 0.012f * t)
        }
    }

    /** Columns, token tiles, focus sleeves and the causal veil (only when content, focus or shift changes). */
    private fun layoutSlots(sh: Float) {
        // columns + tiles
        for (k in 0 until W) {
            val on = k < nv
            val x = slotX(k, sh)
            val s = if (sh > 0f && k == 0) 1f - sh else 1f
            tokPlate[k].visible = on
            val want = if (on) 0.046f else 0f
            if (tokPlate[k].tapRadius != want) tokPlate[k].tapRadius = want     // the adapter rebuilds a collider on every change
            if (on) {
                tokPlate[k].pos = P3(x, TOK_Y, TOK_Z); tokPlate[k].uniformScale(s)
                val c = model.charOf(seq[fv + k])
                tokGlyph[k].setMesh(glyphMesh(c))
                tokGlyph[k].setMat(if (c == '\n') glyphDim else glyphWhite)
                tokPlate[k].setMat(if (k == hl) plateHl else plateMat)
            }
            for (r in 0 until 3) for (c in 0 until NPCA) {
                val n = cells[r][k][c]
                n.visible = on
                if (!on) continue
                n.pos = P3(x, ROW_Y[r] - COL_H / 2 + (c + 0.5f) * PITCH, ROW_Z[r])
                n.scale = P3(s, 1f, 1f)
                n.setMat(cellMats[(cellVal[r][k][c] * 2.5f).roundToInt().coerceIn(-5, 5) + 5])
            }
        }
        ellipsis.visible = fv > 0 || (sh > 0f)
        for (l in 0 until 2) gutterDots[l].visible = fv > 0
        // highlight sleeves + causal veil over the future columns of the rows the highlighted token reads
        val fs = focusSlot()
        for (r in 0 until 3) {
            sleeves[r].visible = phase != Phase.FLY
            sleeves[r].pos = P3(slotX(fs, sh), ROW_Y[r], ROW_Z[r])
        }
        for (r in 0 until 2) {
            val show = hl in 0 until nv - 1
            veils[r].visible = show
            if (show) {
                val x0 = slotX(hl, sh) + SX / 2; val x1 = slotX(nv - 1, sh) + 0.035f
                veils[r].pos = P3((x0 + x1) / 2, ROW_Y[r], ROW_Z[r] + 0.012f)
                veils[r].scale = P3(x1 - x0, COL_H + 0.02f, 0.03f)
            }
        }
    }

    private var picksAtPreset = 0

    /** Pick which attention links to draw (strongest per query and head) and place the pooled threads. */
    private fun placeThreads() {
        val tr = trace ?: return
        val sh = shiftNow()
        val show = phase != Phase.FLY
        val cand = ArrayList<FloatArray>()      // [layer, head, qSlot, kSlot(-1 = earlier), weight, strong]
        val base = fv - ctxStart                // context position of visible slot 0
        val focus = focusSlot()                 // the highlighted token, else the last one (it predicts)
        for (l in 0 until 2) {
            if (layerSel != 2 && layerSel != l) continue
            for (h in 0 until 4) {
                if (!headOn[h]) continue
                for (q in 0 until nv) {
                    val row = tr.att[l][h][base + q]
                    var gut = 0.0; for (j in 0 until base) gut += row[j]
                    val keys = ArrayList<Pair<Int, Double>>()
                    if (gut > 0.0) keys += -1 to gut
                    for (k in 0..q) keys += k to row[base + k]
                    keys.sortByDescending { it.second }
                    fun add(k: Pair<Int, Double>, kind: Float) { cand += floatArrayOf(l.toFloat(), h.toFloat(), q.toFloat(), k.first.toFloat(), k.second.toFloat(), kind) }
                    if (q == focus) keys.filter { it.second >= 0.04 }.forEach { add(it, 2f) }                 // what the focus token reads
                    else {
                        keys.filter { it.first == focus && it.second >= 0.10 }.forEach { add(it, 1f) }      // who reads the focus token
                        keys.take(1).filter { it.first != focus && it.second >= 0.30 }.forEach { add(it, 0f) } // faint context
                    }
                }
            }
        }
        cand.sortWith(compareByDescending<FloatArray> { it[5] }.thenByDescending { it[4] })   // focus first, then strongest
        threadCount = minOf(cand.size, POOL)
        for (i in 0 until POOL) {
            val t = threads[i]
            if (i >= threadCount || !show || grow <= 0.01f) { t.visible = false; continue }
            val c = cand[i]
            val l = c[0].toInt(); val h = c[1].toInt(); val q = c[2].toInt(); val k = c[3].toInt(); val w = c[4]; val kind = c[5].toInt()
            val off = (h - 1.5f) * 0.008f
            val from = if (k < 0) P3(X0 - 0.07f, ROW_Y[l] + COL_H / 2 + 0.004f, ROW_Z[l])
                       else P3(slotX(k, sh) + off, ROW_Y[l] + COL_H / 2 + 0.004f, ROW_Z[l])
            val to = P3(slotX(q, sh) + off, ROW_Y[l + 1] - COL_H / 2 - 0.004f, ROW_Z[l + 1])
            val r = when (kind) { 2 -> 0.0015f + 0.0060f * w; 1 -> 0.0012f + 0.0040f * w; else -> 0.0010f }
            place(t, from, to, r * grow)
            val a = when (kind) { 2 -> 0.40f + 0.60f * w; 1 -> 0.25f + 0.45f * w; else -> 0.10f }
            t.setMat(threadMats[h][(a * 20f).roundToInt().coerceIn(1, 20)])
            t.visible = true
        }
    }
    private var threadCount = 0

    /** Unit cylinder (Y axis) from [a] to [b] with radius [r]. */
    private fun place(n: Node, a: P3, b: P3, r: Float) {
        val d = b - a; val len = d.length
        n.pos = P3((a.x + b.x) / 2, (a.y + b.y) / 2, (a.z + b.z) / 2)
        n.rot = Q.fromTo(0f, 1f, 0f, d.x, d.y, d.z)
        n.scale = P3(maxOf(r, 1e-4f), maxOf(len, 1e-4f), maxOf(r, 1e-4f))
    }

    private fun pct(p: Float): String = when {
        p >= 0.995f -> ">99"
        p < 0.005f -> "<1"
        else -> "${(p * 100).roundToInt()}%".let { if (it.length > 3) it.dropLast(1) else it }
    }

