                lastMsg = Bi("接上【%s】（%.1f%%）—— 整排重新计算".format(show(model.charOf(tok)), p * 100),
                    "Appended choice #%d (%.1f%%) — the whole row recomputes".format(k + 1, p * 100))
            }
            name.startsWith("Tok") -> {
                val k = name.removePrefix("Tok").toIntOrNull() ?: return
                if (k >= nv) return
                highlight(if (hl == k) -1 else k)
                lastMsg = if (hl < 0) Bi("取消高亮", "Highlight off")
