// Transformer · GPT (Vaswani et al. 2017; presentation after 3Blue1Brown's "But what is a GPT?" and
// "Attention in transformers") — a REAL tiny character-level GPT you can watch think.
//
// LESSON: text -> tokens -> vectors; attention lets every token look BACK at earlier ones (never
// forward); the last vector becomes a probability for the next token, and generating = repeat.
//
// SCENE (front view, metres):
//   * the prompt's last 12 tokens stand in a row as glyph tiles (front, bottom); above each, its vector
//     as a column of 6 glowing cells (64 dims -> the 6 main PCA directions of that layer, colour = value)
//   * three rows of columns step up and back: embedding (token + position), after layer 1, after layer 2
//   * between rows, ATTENTION threads: from each token's column in the upper row down to the earlier
//     tokens it reads in the row below; thickness = weight, one colour per head (4 heads); nothing ever
//     points right (causal mask). Pinch a tile: its threads light up and the future is veiled in red
//   * right: the next-token fan — top-10 characters with bars ∝ probability, the temperature knob at
//     its hub (pinch-drag); pinch a bar -> that character flies onto the row, everything recomputes
//   * front shelf: 5 prompt presets; left: head chips H1-H4; bottom right: ▶ generate a sentence
// The model (core/gpt) is trained by tools/train_gpt.py on text generated by a small grammar.

