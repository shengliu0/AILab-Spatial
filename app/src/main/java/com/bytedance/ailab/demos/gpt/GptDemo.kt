    private fun smooth(t: Float) = t * t * (3f - 2f * t)

    private fun quad(u0: Float, v0: Float, u1: Float, v1: Float) = MeshData(
        floatArrayOf(-0.5f, -0.5f, 0f, 0.5f, -0.5f, 0f, 0.5f, 0.5f, 0f, -0.5f, 0.5f, 0f),
        floatArrayOf(0f, 0f, 1f, 0f, 0f, 1f, 0f, 0f, 1f, 0f, 0f, 1f),
        floatArrayOf(u0, v1, u1, v1, u1, v0, u0, v0),
        intArrayOf(0, 1, 2, 0, 2, 3))

    /** Rotate a mesh +90 deg about X: a Y-axis cylinder becomes a disc facing the viewer (+Z). */
    private fun rotX(m: MeshData): MeshData {
        val p = m.pos.copyOf(); val n = m.nrm.copyOf()
        for (i in 0 until m.vertexCount) {
            val y = m.pos[i * 3 + 1]; val z = m.pos[i * 3 + 2]; p[i * 3 + 1] = -z; p[i * 3 + 2] = y
            val ny = m.nrm[i * 3 + 1]; val nz = m.nrm[i * 3 + 2]; n[i * 3 + 1] = -nz; n[i * 3 + 2] = ny
        }
        return MeshData(p, n, m.uv, m.idx)
    }

    /** A static text strip composed from the glyph atlas (preset tags): built once. */
    private fun textImage(s: String): Image {
        val c = atlas.cell; val img = Image(c * s.length, c)
        s.forEachIndexed { i, ch ->
            val g = atlas.indexOf(ch); if (g < 0) return@forEachIndexed
            for (y in 0 until c) for (x in 0 until c) {
                val a = atlas.alpha[g * c * c + y * c + x].toInt() and 0xFF
                img.px[y * img.w + i * c + x] = (a shl 24) or 0xFFFFFF
            }
        }
        return img
    }

    @Suppress("unused") private fun dist(a: P3, b: P3) = sqrt((a.x - b.x) * (a.x - b.x) + (a.y - b.y) * (a.y - b.y) + (a.z - b.z) * (a.z - b.z))
